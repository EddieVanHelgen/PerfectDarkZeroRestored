"""Generate src/mod/render/guest_ip_profile_hooks.inc for pdz_guest_ip_profile (guest_ip_profile.cpp).

A hooked guest function's entry in PPCFuncMappings points at the hook; Rare's original body is __imp__sub_X, which
has no entry. This lists every guest function named in a REX_HOOK_RAW / REX_HOOK under src/ so the profiler can map
the original bodies too. Re-run after adding hooks (a hook missing here only shows its original as 'exe other').

    python -I tools/perf/gen_ip_profile_hooks.py
"""
import os
import re

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
names = set()
pat = re.compile(r"REX_HOOK(?:_RAW)?\(\s*(sub_[0-9A-F]{8})")
for d, _, files in os.walk(os.path.join(root, "src")):
    for f in files:
        if f.endswith((".cpp", ".h", ".inc")):
            with open(os.path.join(d, f), encoding="utf-8", errors="replace") as fh:
                names.update(pat.findall(fh.read()))
# Only guest functions this build's generated code defines (launch-era hooks in files TU3 doesn't build name
# functions that don't exist here). Read-only use of generated/.
init = os.path.join(root, "generated", "default", "perfectdarkzerorecomp_init.cpp")
with open(init, encoding="utf-8", errors="replace") as fh:
    defined = set(re.findall(r"\{ 0x[0-9A-F]{8}, (sub_[0-9A-F]{8}) \}", fh.read()))
missing = sorted(names - defined)
names = sorted(names & defined)
if missing:
    print(len(missing), "hooked names not in this build's generated code (skipped)")
out = os.path.join(root, "src", "mod", "render", "guest_ip_profile_hooks.inc")
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// Generated by tools/perf/gen_ip_profile_hooks.py: the hooked guest functions' original bodies\n")
    fh.write("// (__imp__sub_X) for pdz_guest_ip_profile. %d functions.\n" % len(names))
    fh.write("#ifndef PDZ_IP_HOOK\n#define PDZ_IP_HOOK(name, address)\n#endif\n")
    for n in names:
        fh.write("PDZ_IP_HOOK(%s, 0x%s)\n" % (n, n[4:]))
print(len(names), "hooked functions ->", out)
